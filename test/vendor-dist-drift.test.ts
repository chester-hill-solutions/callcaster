import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, beforeEach, describe, expect, test } from "vitest";

const packages = [
  "vendor/scriptkit/scriptkit-call-script-core",
  "vendor/scriptkit/scriptkit-call-script-react",
  "vendor/chester-hill-solutions/shad-cc",
] as const;
const source = "export const value = 7;\n";
const fixtureBuild = `
import fs from 'node:fs';
fs.rmSync('dist', {recursive: true, force: true});
fs.mkdirSync('dist');
fs.copyFileSync('src/index.js', 'dist/index.js');
`;
let fixture: string;

function write(file: string, contents: string) {
  writeFileSync(join(fixture, file), contents);
}

function run() {
  const result = spawnSync(process.execPath, [join(fixture, "scripts/check-vendor-dist-drift.mjs")], {
    cwd: fixture, encoding: "utf8", timeout: 30_000,
    env: { ...process.env, npm_config_loglevel: "error" },
  });
  expect(result.error).toBeUndefined();
  expect(result.signal).toBeNull();
  expect(result.status).not.toBeNull();
  return { status: result.status, output: result.stdout + result.stderr };
}

beforeEach(() => {
  fixture = mkdtempSync(join(tmpdir(), "callcaster-vendor-drift-"));
  mkdirSync(join(fixture, "scripts"));
  copyFileSync(resolve("scripts/check-vendor-dist-drift.mjs"), join(fixture, "scripts/check-vendor-dist-drift.mjs"));
  for (const pkg of packages) {
    mkdirSync(join(fixture, pkg, "src"), { recursive: true });
    mkdirSync(join(fixture, pkg, "dist"));
    write(`${pkg}/package.json`, JSON.stringify({ private: true, type: "module", scripts: { build: "node build.mjs" } }));
    write(`${pkg}/build.mjs`, fixtureBuild);
    write(`${pkg}/src/index.js`, source);
    write(`${pkg}/dist/index.js`, source);
  }
  write("local-note.txt", "Unrelated work stays here.\n");
});

afterEach(() => rmSync(fixture, { recursive: true, force: true }));

describe("actual vendor drift CLI", () => {
  test("accepts matching output for all three packages without touching source or unrelated work", () => {
    const result = run();
    expect(result.status).toBe(0);
    for (const pkg of packages) {
      expect(result.output).toContain(`${pkg} — dist matches source`);
      expect(readFileSync(join(fixture, pkg, "src/index.js"), "utf8")).toBe(source);
    }
    expect(readFileSync(join(fixture, "local-note.txt"), "utf8")).toBe("Unrelated work stays here.\n");
  });

  test.each(packages)("rejects stale generated bytes in %s", (pkg) => {
    write(`${pkg}/dist/index.js`, "export const value = 999;\n");
    const result = run();
    expect(result.status).toBe(1);
    expect(result.output).toContain(`${pkg}/dist is not what its source builds`);
    expect(result.output).toContain("modified index.js");
    expect(readFileSync(join(fixture, pkg, "src/index.js"), "utf8")).toBe(source);
    expect(readFileSync(join(fixture, "local-note.txt"), "utf8")).toBe("Unrelated work stays here.\n");
  });

  test.each(packages)("rejects a failed build in %s", (pkg) => {
    write(`${pkg}/build.mjs`, "process.exit(12);\n");
    const result = run();
    expect(result.status).toBe(1);
    expect(result.output).toContain(`build failed for ${pkg}`);
  });

  test("rejects a missing generated UI entry", () => {
    rmSync(join(fixture, packages[2], "dist/index.js"));
    const result = run();
    expect(result.status).toBe(1);
    expect(result.output).toContain("added    index.js");
  });

  test("rejects an obsolete UI chunk removed by the configured build", () => {
    write(`${packages[2]}/dist/old-chunk.js`, "export const obsolete = true;\n");
    const result = run();
    expect(result.status).toBe(1);
    expect(result.output).toContain("removed  old-chunk.js");
  });
});
